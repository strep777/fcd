import {spawn} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {mkdirSync,appendFileSync,writeFileSync,existsSync} from 'node:fs';
const root=fileURLToPath(new URL('..',import.meta.url));
const executable=resolve(root,'apps/desktop/src-tauri/target/release/FurryPatternCAD.exe');
if(!existsSync(executable))throw Error('Run npm run build before starting the desktop application');
const env={...process.env,FPCAD_DATA_DIR:process.env.FPCAD_DATA_DIR??resolve(root,'.local/workspace')};
const logDirectory=resolve(root,'test-results/startup');mkdirSync(logDirectory,{recursive:true});
const logFile=resolve(logDirectory,'launcher.log');writeFileSync(logFile,`${new Date().toISOString()}\nTauri: ${executable}\n`);
const child=spawn(executable,process.argv.slice(2),{cwd:root,env,stdio:['inherit','pipe','pipe'],windowsHide:true});
for(const [stream,output] of [[child.stdout,process.stdout],[child.stderr,process.stderr]])stream.on('data',chunk=>{output.write(chunk);appendFileSync(logFile,chunk);});
child.on('error',error=>{console.error(error.message);process.exitCode=1;});
child.on('close',code=>{process.exitCode=code===0?0:1;});
